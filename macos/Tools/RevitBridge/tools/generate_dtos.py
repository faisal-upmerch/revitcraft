#!/usr/bin/env python3
"""Generates src/Schema/ExchangeModel.cs from arcus-exchange.schema.json so the add-in writes exactly the property
names Arcus reads. Run from Tools/RevitBridge:  python3 tools/generate_dtos.py"""
import json, os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
schema = json.load(open(os.path.join(root, "arcus-exchange.schema.json")))
defs = schema["$defs"]

# Definitions that are value shapes, not classes.
special = {
    "id": "string?", "uniqueId": "string?", "point2": "double[]?", "point3": "double[]?",
    "scalar": "object?", "value": "object?", "values": "Dictionary<string, object?>?",
    "loops": "List<List<XCurve>>?", "scalarPoint": "object[]?",
}

def pascal(n): return n[0].upper() + n[1:]
def cls(n): return "ExchangeDocument" if n == "$root" else "X" + pascal(n)

def csType(s):
    if "$ref" in s:
        name = s["$ref"].split("/")[-1]
        return special.get(name, cls(name) + "?")
    if "const" in s or "enum" in s: return "string?"
    t = s.get("type")
    if t == "number": return "double?"
    if t == "integer": return "int?"
    if t == "boolean": return "bool?"
    if t == "string": return "string?"
    if t == "array":
        inner = csType(s["items"]).rstrip("?")
        if inner == "double": return "List<double>?"
        if inner == "int": return "List<int>?"
        return "List<%s>?" % inner
    if t == "object": return "Dictionary<string, object?>?"
    return "object?"

out = ["// <auto-generated> by tools/generate_dtos.py from arcus-exchange.schema.json. Do not edit by hand. </auto-generated>",
       "// Arcus Exchange 1.0 data transfer objects. Null properties are omitted when serialized.",
       "#nullable enable", "using System.Collections.Generic;", "using System.Text.Json.Serialization;", "",
       "namespace Arcus.Bridge.Schema", "{"]
def emit(name, s):
    out.append("    public sealed class %s" % cls(name))
    out.append("    {")
    for p, ps in s["properties"].items():
        out.append('        [JsonPropertyName("%s")] public %s %s { get; set; }' % (p, csType(ps), pascal(p)))
    out.append("    }")
    out.append("")
emit("$root", schema)
for n, s in defs.items():
    if n in special or "properties" not in s: continue
    emit(n, s)
out.append("}")
open(os.path.join(root, "src", "Schema", "ExchangeModel.cs"), "w").write("\n".join(out) + "\n")
print("wrote", len(out), "lines")
