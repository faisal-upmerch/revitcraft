#!/usr/bin/env bash
# Regenerates THIRD_PARTY_LICENSES.txt: the licence texts of every crate compiled into arcus-dwg (acadrust under
# MPL-2.0 and its MIT/Apache/BSD/Zlib dependencies), taken from the crate sources cargo downloaded for Cargo.lock.
# Run it after changing Cargo.toml or Cargo.lock; build_and_run.sh ships the file inside Arcus.app.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CARGO="${CARGO:-$HOME/.cargo/bin/cargo}"
export PATH="$HOME/.cargo/bin:$PATH"
cd "$HERE"
REGISTRY="${CARGO_HOME:-$HOME/.cargo}/registry/src"
OUT="$HERE/THIRD_PARTY_LICENSES.txt.tmp"
{
  echo "Third-party software in arcus-dwg, the DWG helper bundled with Arcus"
  echo "Generated by Tools/DWGHelper/collect_licenses.sh from Cargo.lock. Crate, version, licence, then the licence texts."
  echo "acadrust is used unmodified under the Mozilla Public License 2.0; its source is at https://github.com/hakanaktt/acadrust"
  echo "and https://crates.io/crates/acadrust/0.6.5."
  echo
} > "$OUT"
"$CARGO" tree --locked --offline -e normal --prefix none --format '{p}|{l}' | sed 's/ (\*)$//; s/ (proc-macro)//' | sort -u | while IFS='|' read -r pkg lic; do
  name="${pkg%% *}"; ver="${pkg#* v}"; ver="${ver%% *}"
  [[ "$name" == "arcus-dwg" ]] && continue
  dir="$(ls -d "$REGISTRY"/*/"$name-$ver" 2>/dev/null | head -1 || true)"
  {
    echo "================================================================================"
    echo "$name $ver — $lic"
    echo "================================================================================"
    found=0
    if [[ -n "$dir" ]]; then
      for f in "$dir"/LICENSE* "$dir"/LICENCE* "$dir"/COPYING* "$dir"/NOTICE* "$dir"/UNLICENSE* "$dir"/license*; do
        [[ -f "$f" ]] || continue
        echo "--- $(basename "$f") ---"
        cat "$f"
        echo
        found=1
      done
    fi
    [[ "$found" == "1" ]] || echo "(No licence file in the crate; licence per its Cargo.toml: $lic)"
    echo
  } >> "$OUT"
done
mv "$OUT" "$HERE/THIRD_PARTY_LICENSES.txt"
echo "✓ Wrote $HERE/THIRD_PARTY_LICENSES.txt"
