import Foundation
import ArcusGeometry
import ArcusCalc
import ArcusDomain

/// Converts an exchange family (`XFamily`) to an Arcus `FamilyDefinition`.
///
/// Arcus family solids are extrusions of an XY profile between two Z bounds. Exchange extrusions along Z map exactly
/// (parametric vertices, circles and reference-plane bounds are kept). Extrusions along X or Y map exactly when their
/// profile is an axis-aligned rectangle; other shapes (and tessellated forms) are approximated by boxes of the same
/// extents or skipped, per `ExchangeImportOptions.unsupportedFamilyGeometry`, and reported.
enum ExchangeFamilyConverter {
    struct Output {
        var definition: FamilyDefinition
        var instanceCategory: ArcusDomain.Category
        var warnings: [String] = []
        var approximated = 0
        var skipped = 0
        /// Type name → (material parameter name → exchange material id).
        var typeMaterials: [String: [String: String]] = [:]
        /// Synthesized "fixed material" parameter name → exchange material id.
        var fixedMaterials: [String: String] = [:]
        /// Exchange type id → Arcus family type name.
        var typeNames: [String: String] = [:]
        /// Exchange type id → extra text (type mark, description, fire rating).
        var typeExtras: [String: XFamilyType] = [:]
        /// True when the family has at least one non-void solid.
        var hasGeometry = false
        /// True when the geometry was generated by Arcus because none was exported.
        var synthesized = false
    }

    static func categoryAndTemplate(_ key: String?) -> (ArcusDomain.Category, FamilyTemplate, known: Bool) {
        switch key ?? "" {
        case "doors": (.doors, .door, true)
        case "windows": (.windows, .window, true)
        case "furniture", "furnitureSystems": (.furniture, .furniture, true)
        case "casework": (.casework, .casework, true)
        case "genericModels": (.genericModels, .genericModel, true)
        case "columns": (.columns, .column, true)
        case "structuralColumns": (.structuralColumns, .structuralColumn, true)
        case "structuralFraming": (.structuralFraming, .structuralFraming, true)
        case "plumbingFixtures": (.plumbingFixtures, .plumbingFixture, true)
        case "specialtyEquipment": (.specialtyEquipment, .genericModel, true)
        case "parking": (.parking, .genericModel, true)
        default: (.genericModels, .genericModel, false)
        }
    }

    static func paramType(_ s: String?) -> ParamType? {
        switch (s ?? "").lowercased() {
        case "length": .length
        case "area": .area
        case "volume": .volume
        case "angle": .angle
        case "slope": .slope
        case "number": .number
        case "integer": .integer
        case "percentage": .percentage
        case "currency": .currency
        case "text": .text
        case "multilinetext": .multilineText
        case "yesno", "bool", "boolean": .bool
        case "url": .url
        case "material": .elementRef(.materials)
        default: nil
        }
    }

    static func group(_ s: String?) -> ParameterGroup {
        switch (s ?? "").lowercased() {
        case "constraints": .constraints
        case "construction": .construction
        case "graphics": .graphics
        case "materials": .materials
        case "dimensions": .dimensions
        case "structural": .structural
        case "identity": .identity
        case "phasing": .phasing
        case "text": .text
        case "ifc": .ifc
        default: .other
        }
    }

    static func strength(_ s: String?) -> ReferenceStrength {
        switch (s ?? "").lowercased() {
        case "notareference": .notAReference
        case "strong": .strong
        case "left": .left
        case "centerleftright": .centerLeftRight
        case "right": .right
        case "front": .front
        case "centerfrontback": .centerFrontBack
        case "back": .back
        case "bottom": .bottom
        case "centerelevation": .centerElevation
        case "top": .top
        default: .weak
        }
    }

    static func subcategory(_ s: String?) -> FamilySubcategory {
        guard let s = s?.trimmingCharacters(in: .whitespaces).lowercased(), !s.isEmpty else { return .general }
        if let m = FamilySubcategory.allCases.first(where: { $0.rawValue.lowercased() == s }) { return m }
        if s.contains("swing") { return s.contains("elev") ? .elevationSwing : .swing }
        if s.contains("frame") || s.contains("mullion") { return .frame }
        if s.contains("glass") || s.contains("glazing") { return .glass }
        if s.contains("panel") { return .panel }
        if s.contains("hidden") { return .hidden }
        if s.contains("sill") || s.contains("head") { return .sill }
        if s.contains("opening") { return .opening }
        return .general
    }

    static func detailLevels(_ a: [String]?) -> Set<DetailLevel> {
        guard let a else { return [.coarse, .medium, .fine] }
        var out: Set<DetailLevel> = []
        for s in a {
            switch s.lowercased() {
            case "coarse": out.insert(.coarse)
            case "medium": out.insert(.medium)
            case "fine": out.insert(.fine)
            default: break
            }
        }
        return out.isEmpty ? [.coarse, .medium, .fine] : out
    }

    /// Formats a length for a family expression (plain decimal, no exponent).
    static func fmt(_ d: Double) -> String {
        guard d.isFinite else { return "0" }
        var s = String(format: "%.9f", d)
        while s.contains(".") && (s.hasSuffix("0") || s.hasSuffix(".")) { s.removeLast() }
        return s == "-0" || s.isEmpty ? "0" : s
    }

    // MARK: Conversion

    static func convert(_ f: XFamily, materialName: (String) -> String?, options: ExchangeImportOptions) -> Output {
        let rawName = f.name?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        let name = rawName.isEmpty ? "Imported Family" : String(rawName.prefix(200))
        let (category, template, known) = categoryAndTemplate(f.category)
        var def = FamilyDefinition(name: name, template: template)
        def.description = f.description ?? ""
        def.manufacturer = f.manufacturer ?? ""
        var out = Output(definition: def, instanceCategory: category)
        func warn(_ m: String) { out.warnings.append("Family “\(name)”: \(m)") }
        if !known {
            warn("category “\(f.revitCategory ?? f.category ?? "unknown")” has no Arcus equivalent; it was imported as a Generic Model.")
        }

        // Parameters.
        var params: [FamilyParameter] = []
        var seen = Set<String>()
        var builtInNames: [String: String] = [:]
        for p in f.parameters ?? [] {
            guard let n = p.name?.trimmingCharacters(in: .whitespacesAndNewlines), !n.isEmpty, n.count <= 200 else {
                warn("a parameter without a name was skipped."); continue
            }
            guard seen.insert(n).inserted else { warn("duplicate parameter “\(n)” was skipped."); continue }
            guard let t = paramType(p.dataType) else {
                warn("parameter “\(n)” has type “\(p.dataType ?? "unknown")”, which Arcus families don't support; it was skipped.")
                out.skipped += 1
                continue
            }
            var fp = FamilyParameter(name: n, type: t, isInstance: p.isInstance ?? false, group: group(p.group))
            if let b = p.builtIn?.lowercased() { builtInNames[b] = n }
            let isWH = (template.isHostedInWall && (n == "Width" || n == "Height")) || p.builtIn != nil
            fp.isBuiltIn = (p.isBuiltIn ?? false) || isWH
            if let formula = p.formula?.trimmingCharacters(in: .whitespacesAndNewlines), !formula.isEmpty { fp.formula = formula }
            params.append(fp)
        }
        let names = Set(params.map(\.name))
        for i in params.indices {
            guard let formula = params[i].formula else { continue }
            do { _ = try Formula(formula, knownNames: names) } catch {
                warn("the formula of “\(params[i].name)” (\(formula)) could not be read (\(error)); the parameter keeps its type values instead.")
                params[i].formula = nil
                out.approximated += 1
            }
        }
        def.parameters = params
        let paramByName = Dictionary(params.map { ($0.name, $0) }, uniquingKeysWith: { a, _ in a })

        // Types.
        var typeNamesSeen = Set<String>()
        for (k, t) in (f.types ?? []).enumerated() {
            var tn = t.name?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            if tn.isEmpty { tn = "Type \(k + 1)" }
            var unique = tn
            var n = 2
            while typeNamesSeen.contains(unique) { unique = "\(tn) (\(n))"; n += 1 }
            typeNamesSeen.insert(unique)
            var values: [String: ParamValue] = [:]
            for (pn, v) in t.values ?? [:] {
                guard let p = paramByName[pn], p.formula == nil else { continue }
                if case .elementRef = p.type {
                    if case .material(let mid) = v { out.typeMaterials[unique, default: [:]][pn] = mid }
                    continue
                }
                if let pv = paramValue(v, type: p.type) { values[pn] = pv }
            }
            def.types.append(FamilyTypeDefinition(name: unique, values: values))
            if let id = t.id { out.typeNames[id] = unique; out.typeExtras[id] = t }
        }
        if def.types.isEmpty {
            def.types = [FamilyTypeDefinition(name: name, values: [:])]
            warn("no types were exported; a type named “\(name)” was created.")
        }

        // Reference planes.
        var planeNames = Set<String>()
        for (k, p) in (f.referencePlanes ?? []).enumerated() {
            guard let axis = FamilyAxis(rawValue: (p.axis ?? "").uppercased()) else {
                warn("reference plane “\(p.name ?? "\(k + 1)")” is not aligned with the family axes and was skipped.")
                out.skipped += 1
                continue
            }
            var pn = p.name?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            if pn.isEmpty { pn = "Reference Plane \(k + 1)" }
            var unique = pn
            var n = 2
            while planeNames.contains(unique) { unique = "\(pn) (\(n))"; n += 1 }
            let offset: String
            switch p.offset ?? .number(0) {
            case .number(let d): offset = fmt(d)
            case .expr(let e):
                if (try? Formula(e, knownNames: names)) != nil { offset = e } else {
                    warn("the position of reference plane “\(unique)” (\(e)) could not be read; it was placed at the origin.")
                    offset = "0"
                    out.approximated += 1
                }
            case .plane:
                warn("reference plane “\(unique)” is positioned by another plane, which Arcus doesn't support; it was placed at the origin.")
                offset = "0"
                out.approximated += 1
            }
            planeNames.insert(unique)
            def.referencePlanes.append(FamilyReferencePlane(name: unique, axis: axis, offset: offset, strength: strength(p.strength),
                                                            definesOrigin: p.definesOrigin ?? false))
        }

        let ctx = ScalarContext(definition: def)

        // Geometry.
        var fixedByMaterial: [String: String] = [:]
        for (k, g) in (f.geometry ?? []).enumerated() {
            let gname = g.name?.isEmpty == false ? g.name! : "Solid \(k + 1)"
            let isVoid = g.isVoid ?? false
            var material: String?
            if let mp = g.materialParameter {
                if let p = paramByName[mp], case .elementRef = p.type { material = mp } else {
                    warn("“\(gname)” uses material parameter “\(mp)”, which was not exported as a material parameter.")
                }
            }
            if material == nil, !isVoid, let mid = g.materialId {
                if let existing = fixedByMaterial[mid] { material = existing } else {
                    var pn = "Material: \(materialName(mid) ?? mid)"
                    while paramByName[pn] != nil || def.parameters.contains(where: { $0.name == pn }) { pn += "*" }
                    def.parameters.append(FamilyParameter(name: pn, type: .elementRef(.materials), isInstance: false, group: .materials))
                    fixedByMaterial[mid] = pn
                    out.fixedMaterials[pn] = mid
                    material = pn
                }
            }
            let shapes: [ShapeResult]
            switch (g.kind ?? "extrusion").lowercased() {
            case "extrusion": shapes = extrusion(g, ctx: ctx, name: gname)
            case "mesh": shapes = meshBox(g, name: gname)
            default: shapes = [ShapeResult(warning: "“\(gname)” has unknown geometry kind “\(g.kind ?? "")” and was skipped.", skipped: true)]
            }
            for (j, r) in shapes.enumerated() {
                if let w = r.warning { warn(w) }
                if r.skipped { out.skipped += 1; continue }
                guard let profile = r.profile, let z0 = r.zMin, let z1 = r.zMax else { continue }
                if r.approximated {
                    if isVoid {
                        warn("void “\(gname)” can't be represented exactly and was skipped.")
                        out.skipped += 1
                        continue
                    }
                    if options.unsupportedFamilyGeometry == .skip {
                        warn("“\(gname)” can't be represented exactly and was skipped.")
                        out.skipped += 1
                        continue
                    }
                    out.approximated += 1
                }
                if case .polygon(let pts) = profile, pts.count < 3 { continue }
                var solid = FamilySolid(name: shapes.count > 1 ? "\(gname) (\(j + 1))" : gname, profile: profile, zMin: z0, zMax: z1,
                                        materialParameter: material, subcategory: subcategory(g.subcategory), isVoid: isVoid,
                                        visibleInPlan: g.visibleInPlan ?? true)
                solid.id = "\(name)/solid/\(k)/\(j)"
                solid.visibleAt = detailLevels(g.visibleAt)
                if let vp = g.visibilityParameter {
                    if paramByName[vp]?.type == .bool { solid.visibilityParameter = vp } else {
                        warn("“\(gname)” visibility parameter “\(vp)” is not a Yes/No parameter and was ignored.")
                    }
                }
                def.solids.append(solid)
                if !isVoid { out.hasGeometry = true }
            }
        }
        if def.solids.contains(where: { $0.isVoid && !$0.profile.isExtrusion }) {
            warn("Arcus keeps swept, blended and revolved voids in the family definition but only void extrusions cut the family’s solids.")
        }

        // Plan symbolic lines.
        for (k, l) in (f.planLines ?? []).enumerated() {
            guard let c = l.curve, var line = familyLine(c, ctx: ctx) else {
                warn("plan line \(k + 1) could not be read and was skipped."); out.skipped += 1; continue
            }
            line.id = "\(name)/line/\(k)"
            line.subcategory = subcategory(l.subcategory)
            line.visibleAt = detailLevels(l.visibleAt)
            def.planLines.append(line)
        }

        // Dimensions between planes.
        for (k, d) in (f.dimensions ?? []).enumerated() {
            guard let a = d.planeA, let b = d.planeB, planeNames.contains(a), planeNames.contains(b) else { continue }
            var dim = FamilyDimension(planeA: a, planeB: b, labelParameter: d.label.flatMap { paramByName[$0] != nil ? $0 : nil })
            dim.id = "\(name)/dim/\(k)"
            def.dimensions.append(dim)
        }

        // Opening for hosted families.
        if template.isHostedInWall || f.opening != nil {
            def.opening = opening(f.opening, def: def, ctx: ctx, builtIn: builtInNames, warn: warn)
        }

        // Doors/windows without exported geometry get a simple parametric panel so they stay native and editable.
        if template.isHostedInWall && !out.hasGeometry {
            synthesizeInsertGeometry(&def, builtIn: builtInNames)
            out.synthesized = true
            out.hasGeometry = true
            if def.opening == nil { def.opening = opening(nil, def: def, ctx: ScalarContext(definition: def), builtIn: builtInNames, warn: warn) }
            warn("no geometry was exported, so Arcus generated a simple panel sized by its Width and Height.")
        }

        // Evaluate each type to surface problems now rather than on first placement.
        for t in def.types.prefix(50) {
            let ev = FamilyEvaluator.evaluate(def, typeName: t.name)
            for e in ev.errors.prefix(5) { warn("type “\(t.name)”: \(e)") }
        }
        out.definition = def
        return out
    }

    static func paramValue(_ v: XValue, type: ParamType) -> ParamValue? {
        switch (v, type) {
        case (.number(let d), _) where !d.isFinite: return nil
        case (.number(let d), .integer): return .int(Int(max(-1e15, min(1e15, d)).rounded()))
        case (.number(let d), .bool): return .bool(d != 0)
        case (.number(let d), .text), (.number(let d), .multilineText), (.number(let d), .url): return .text(fmt(d))
        case (.number(let d), _): return .double(d)
        case (.bool(let b), .bool): return .bool(b)
        case (.bool(let b), .text), (.bool(let b), .multilineText): return .text(b ? "Yes" : "No")
        case (.bool(let b), _): return type.isNumeric ? .double(b ? 1 : 0) : nil
        case (.text(let s), .text), (.text(let s), .multilineText), (.text(let s), .url): return .text(String(s.prefix(10_000)))
        case (.text(let s), .choice): return .text(s)
        case (.text(let s), .bool): return ParamValue.text(s).boolValue.map { .bool($0) }
        case (.text(let s), .integer): return Int(s).map { .int($0) }
        case (.text(let s), _): return Double(s).flatMap { $0.isFinite ? .double($0) : nil }
        default: return nil
        }
    }

    // MARK: Scalars

    /// Evaluates scalars against the first type's parameter values and plane positions.
    struct ScalarContext {
        var names: Set<String>
        var values: [String: FormulaValue]
        var planes: [String: Double]

        init(definition def: FamilyDefinition) {
            names = Set(def.parameters.map(\.name))
            let ev = FamilyEvaluator.evaluate(def, typeName: def.types.first?.name ?? "")
            values = ev.values
            planes = ev.planes
        }

        func number(_ s: XScalar) -> Double? {
            switch s {
            case .number(let d): return d.isFinite ? d : nil
            case .plane(let p): return planes[p]
            case .expr(let e):
                if let d = Double(e) { return d }
                guard let f = try? Formula(e, knownNames: names), let v = try? f.evaluate(units: .metric, { values[$0] }) else { return nil }
                switch v {
                case .quantity(let d, _): return d.isFinite ? d : nil
                case .bool(let b): return b ? 1 : 0
                case .text: return nil
                }
            }
        }

        /// The scalar as a family bound, or nil when it references unknown names or planes.
        func bound(_ s: XScalar) -> FamilyBound? {
            switch s {
            case .number(let d): return d.isFinite ? .expr(fmt(d)) : nil
            case .plane(let p): return planes[p] != nil ? .plane(p) : nil
            case .expr(let e):
                if let d = Double(e) { return .expr(fmt(d)) }
                return (try? Formula(e, knownNames: names)) != nil ? .expr(e) : nil
            }
        }
    }

    /// A 2D vertex carrying both its parametric scalars and numeric position.
    struct Vertex {
        var u: XScalar, v: XScalar
        var p: Vec2
    }

    struct ShapeResult {
        var profile: FamilySolid.Profile?
        var zMin: FamilyBound?
        var zMax: FamilyBound?
        var approximated = false
        var warning: String?
        var skipped = false
        init(profile: FamilySolid.Profile, zMin: FamilyBound, zMax: FamilyBound, approximated: Bool = false, warning: String? = nil) {
            self.profile = profile; self.zMin = zMin; self.zMax = zMax; self.approximated = approximated; self.warning = warning
        }
        init(warning: String, skipped: Bool) { self.warning = warning; self.skipped = skipped }
    }

    /// One loop with its vertices (in order) and numeric polygon. `circle` is set for loops that are one full circle.
    struct Loop {
        var vertices: [Vertex]
        var polygon: Polygon2
        var circle: (center: [XScalar], radius: XScalar)?
        var hasParametricArc = false
    }

    static func scalarPair(_ a: [XScalar]?, _ ctx: ScalarContext) -> Vertex? {
        guard let a, a.count >= 2, let x = ctx.number(a[0]), let y = ctx.number(a[1]) else { return nil }
        return Vertex(u: a[0], v: a[1], p: Vec2(x, y))
    }

    /// Orders a loop head to tail and returns vertices (arcs tessellated numerically).
    static func loop(_ curves: [XProfileCurve], ctx: ScalarContext) -> Loop? {
        guard !curves.isEmpty, curves.count <= 10_000 else { return nil }
        // Full circle given as one curve.
        if curves.count == 1, curves[0].type == "circle", let c = curves[0].center, c.count >= 2, let r = curves[0].radius,
           let cc = scalarPair(c, ctx), let rr = ctx.number(r), rr > Tolerance.length {
            let pts = Arc2(center: cc.p, radius: rr, startAngle: 0, sweep: Angle.twoPi).tessellate(chordTolerance: 0.002).dropLast()
            return Loop(vertices: pts.map { Vertex(u: .number($0.x), v: .number($0.y), p: $0) }, polygon: Polygon2(Array(pts)), circle: (c, r))
        }
        struct Piece { var a: Vertex; var b: Vertex; var interior: [Vec2]; var arc: Arc2?; var src: XProfileCurve }
        var pieces: [Piece] = []
        for c in curves {
            guard let a = scalarPair(c.start, ctx), let b = scalarPair(c.end, ctx) else { return nil }
            if c.type == "arc", let m = scalarPair(c.mid, ctx), let arc = Arc2(through: a.p, m.p, b.p) {
                let t = arc.tessellate(chordTolerance: 0.002)
                pieces.append(Piece(a: a, b: b, interior: Array(t.dropFirst().dropLast()), arc: arc, src: c))
            } else {
                pieces.append(Piece(a: a, b: b, interior: [], arc: nil, src: c))
            }
        }
        // Chain head to tail.
        let tol = 1e-4
        var ordered: [Piece] = [pieces.removeFirst()]
        while !pieces.isEmpty {
            let end = ordered.last!.b.p
            if let i = pieces.firstIndex(where: { $0.a.p.isAlmostEqual(end, tolerance: tol) }) {
                ordered.append(pieces.remove(at: i))
            } else if let i = pieces.firstIndex(where: { $0.b.p.isAlmostEqual(end, tolerance: tol) }) {
                var p = pieces.remove(at: i)
                swap(&p.a, &p.b)
                p.interior.reverse()
                ordered.append(p)
            } else {
                return nil
            }
        }
        guard ordered.last!.b.p.isAlmostEqual(ordered[0].a.p, tolerance: tol) else { return nil }
        var verts: [Vertex] = []
        var parametricArc = false
        for p in ordered {
            verts.append(p.a)
            if p.arc != nil, [p.a.u, p.a.v, p.b.u, p.b.v].contains(where: { if case .number = $0 { return false }; return true }) {
                parametricArc = true
            }
            verts.append(contentsOf: p.interior.map { Vertex(u: .number($0.x), v: .number($0.y), p: $0) })
        }
        // Two or more arcs sharing a center and radius that close a full turn form a circle.
        var circle: (center: [XScalar], radius: XScalar)?
        let arcs = ordered.compactMap(\.arc)
        if arcs.count == ordered.count, let first = arcs.first,
           arcs.allSatisfy({ $0.center.isAlmostEqual(first.center, tolerance: tol) && abs($0.radius - first.radius) < tol }),
           abs(abs(arcs.reduce(0) { $0 + $1.sweep }) - Angle.twoPi) < 1e-3 {
            let src = ordered[0].src
            let center = src.center ?? [.number(first.center.x), .number(first.center.y)]
            circle = (center, src.radius ?? .number(first.radius))
            parametricArc = false
        }
        return Loop(vertices: verts, polygon: Polygon2(verts.map(\.p)), circle: circle, hasParametricArc: parametricArc)
    }

    /// Extent along the extrusion axis as ordered bounds.
    static func extent(_ g: XFamilyGeometry, ctx: ScalarContext) -> (FamilyBound, FamilyBound)? {
        guard let e = g.extent, e.count == 2, let a = ctx.number(e[0]), let b = ctx.number(e[1]),
              let ba = ctx.bound(e[0]), let bb = ctx.bound(e[1]) else { return nil }
        return a <= b ? (ba, bb) : (bb, ba)
    }

    static func extrusion(_ g: XFamilyGeometry, ctx: ScalarContext, name: String) -> [ShapeResult] {
        guard let (lo, hi) = extent(g, ctx: ctx) else { return [ShapeResult(warning: "“\(name)” has no readable extrusion extent and was skipped.", skipped: true)] }
        let rawLoops = g.loops ?? []
        guard !rawLoops.isEmpty else { return [ShapeResult(warning: "“\(name)” has no profile and was skipped.", skipped: true)] }
        var loops: [Loop] = []
        for l in rawLoops {
            guard let lp = loop(l, ctx: ctx), !lp.polygon.isDegenerate else {
                return [ShapeResult(warning: "“\(name)” has a profile loop that is open or encloses no area; it was skipped.", skipped: true)]
            }
            loops.append(lp)
        }
        // Outer loops are those not inside another loop.
        var outers: [Loop] = []
        var holes = 0
        for (i, l) in loops.enumerated() {
            let inside = loops.enumerated().contains { j, o in j != i && o.polygon.area > l.polygon.area && o.polygon.contains(l.polygon.points[0]) }
            if inside { holes += 1 } else { outers.append(l) }
        }
        let holeNote = holes > 0 ? "“\(name)” has \(holes) inner loop\(holes == 1 ? "" : "s") (holes); Arcus family solids have no holes, so they were filled." : nil
        let axis = (g.extrusionAxis ?? "z").lowercased()
        var results: [ShapeResult] = []
        for l in outers {
            switch axis {
            case "z":
                let profile: FamilySolid.Profile
                if let c = l.circle, let cx = ctx.bound(c.center[0]), let cy = ctx.bound(c.center[1]), case .expr(let r)? = ctx.bound(c.radius) {
                    profile = .circle(center: FamilyPoint(cx, cy), radius: r)
                } else {
                    var pts: [FamilyPoint] = []
                    for v in l.vertices {
                        pts.append(FamilyPoint(ctx.bound(v.u) ?? .expr(fmt(v.p.x)), ctx.bound(v.v) ?? .expr(fmt(v.p.y))))
                    }
                    profile = .polygon(pts)
                }
                var r = ShapeResult(profile: profile, zMin: lo, zMax: hi, approximated: holes > 0, warning: holeNote)
                if l.hasParametricArc {
                    r.warning = [holeNote, "“\(name)” has arcs whose points depend on parameters; the arcs keep their exported size."].compactMap { $0 }.joined(separator: " ")
                }
                results.append(r)
            case "x", "y":
                // Profile coordinates are (x, z) for axis y and (y, z) for axis x.
                let rect = isAxisAlignedRectangle(l)
                guard let minU = l.vertices.min(by: { $0.p.x < $1.p.x }), let maxU = l.vertices.max(by: { $0.p.x < $1.p.x }),
                      let minV = l.vertices.min(by: { $0.p.y < $1.p.y }), let maxV = l.vertices.max(by: { $0.p.y < $1.p.y }) else { continue }
                let u0 = ctx.bound(minU.u) ?? .expr(fmt(minU.p.x)), u1 = ctx.bound(maxU.u) ?? .expr(fmt(maxU.p.x))
                let v0 = ctx.bound(minV.v) ?? .expr(fmt(minV.p.y)), v1 = ctx.bound(maxV.v) ?? .expr(fmt(maxV.p.y))
                let profile: FamilySolid.Profile = axis == "y"
                    ? .rectangle(xMin: u0, xMax: u1, yMin: lo, yMax: hi)
                    : .rectangle(xMin: lo, xMax: hi, yMin: u0, yMax: u1)
                let note = rect ? holeNote : "“\(name)” is extruded horizontally from a non-rectangular profile; it was approximated by a box."
                results.append(ShapeResult(profile: profile, zMin: v0, zMax: v1, approximated: !rect || holes > 0, warning: note))
            default:
                return [ShapeResult(warning: "“\(name)” has an unknown extrusion axis “\(axis)” and was skipped.", skipped: true)]
            }
        }
        return results
    }

    static func isAxisAlignedRectangle(_ l: Loop) -> Bool {
        guard l.circle == nil, l.vertices.count == 4 else { return false }
        let p = l.vertices.map(\.p)
        for i in 0..<4 {
            let d = p[(i + 1) % 4] - p[i]
            if abs(d.x) > 1e-6 && abs(d.y) > 1e-6 { return false }
        }
        return true
    }

    static func meshBox(_ g: XFamilyGeometry, name: String) -> [ShapeResult] {
        guard let pos = g.positions, pos.count >= 9, pos.count % 3 == 0, pos.count <= 30_000_000, pos.allSatisfy({ $0.isFinite && abs($0) < 1e5 }) else {
            return [ShapeResult(warning: "“\(name)” has no usable mesh and was skipped.", skipped: true)]
        }
        var lo = Vec3(.infinity, .infinity, .infinity), hi = Vec3(-.infinity, -.infinity, -.infinity)
        for i in stride(from: 0, to: pos.count, by: 3) {
            lo = Vec3(min(lo.x, pos[i]), min(lo.y, pos[i + 1]), min(lo.z, pos[i + 2]))
            hi = Vec3(max(hi.x, pos[i]), max(hi.y, pos[i + 1]), max(hi.z, pos[i + 2]))
        }
        guard hi.x - lo.x > Tolerance.length, hi.y - lo.y > Tolerance.length, hi.z - lo.z > Tolerance.length else {
            return [ShapeResult(warning: "“\(name)” is flat and was skipped.", skipped: true)]
        }
        let kind = g.sourceKind.map { " (\($0))" } ?? ""
        return [ShapeResult(profile: .rectangle(xMin: .expr(fmt(lo.x)), xMax: .expr(fmt(hi.x)), yMin: .expr(fmt(lo.y)), yMax: .expr(fmt(hi.y))),
                            zMin: .expr(fmt(lo.z)), zMax: .expr(fmt(hi.z)), approximated: true,
                            warning: "“\(name)”\(kind) was exported as a mesh; Arcus approximated it by a box of the same size.")]
    }

    static func familyLine(_ c: XProfileCurve, ctx: ScalarContext) -> FamilyLine? {
        guard let a = scalarPair(c.start, ctx), let b = scalarPair(c.end, ctx) else {
            if c.type == "circle", let cc = c.center, cc.count >= 2, let x = ctx.bound(cc[0]), let y = ctx.bound(cc[1]), let r = c.radius, case .expr(let rs)? = ctx.bound(r) {
                return FamilyLine(shape: .arc(center: FamilyPoint(x, y), radius: rs, startDegrees: "0", sweepDegrees: "360"))
            }
            return nil
        }
        if c.type == "arc", let m = scalarPair(c.mid, ctx), let arc = Arc2(through: a.p, m.p, b.p) {
            let center: FamilyPoint
            if let cc = c.center, cc.count >= 2, let x = ctx.bound(cc[0]), let y = ctx.bound(cc[1]) { center = FamilyPoint(x, y) } else {
                center = FamilyPoint(.expr(fmt(arc.center.x)), .expr(fmt(arc.center.y)))
            }
            var radius = fmt(arc.radius)
            if let r = c.radius, case .expr(let rs)? = ctx.bound(r) { radius = rs }
            return FamilyLine(shape: .arc(center: center, radius: radius, startDegrees: fmt(arc.startAngle * 180 / .pi), sweepDegrees: fmt(arc.sweep * 180 / .pi)))
        }
        guard !a.p.isAlmostEqual(b.p, tolerance: Tolerance.length) else { return nil }
        let pa = FamilyPoint(ctx.bound(a.u) ?? .expr(fmt(a.p.x)), ctx.bound(a.v) ?? .expr(fmt(a.p.y)))
        let pb = FamilyPoint(ctx.bound(b.u) ?? .expr(fmt(b.p.x)), ctx.bound(b.v) ?? .expr(fmt(b.p.y)))
        return FamilyLine(shape: .line(pa, pb))
    }

    static func opening(_ o: XOpening?, def: FamilyDefinition, ctx: ScalarContext, builtIn: [String: String], warn: (String) -> Void) -> FamilyOpening? {
        if let o, let a = o.xMin.flatMap(ctx.bound), let b = o.xMax.flatMap(ctx.bound), let c = o.zMin.flatMap(ctx.bound), let d = o.zMax.flatMap(ctx.bound) {
            return FamilyOpening(xMin: a, xMax: b, zMin: c, zMax: d)
        }
        if o != nil { warn("the exported wall opening could not be read; it was derived from the family instead.") }
        func plane(_ s: ReferenceStrength) -> FamilyBound? { def.referencePlanes.first { $0.strength == s }.map { .plane($0.name) } }
        let width = builtIn["width"] ?? "Width", height = builtIn["height"] ?? "Height"
        let hasW = def.parameter(named: width)?.type == .length, hasH = def.parameter(named: height)?.type == .length
        let xMin = plane(.left) ?? (hasW ? .expr("-(\(width)) / 2") : nil)
        let xMax = plane(.right) ?? (hasW ? .expr("(\(width)) / 2") : nil)
        let zMin = plane(.bottom) ?? .expr("0")
        let zMax = plane(.top) ?? (hasH ? .expr(height) : nil)
        if let xMin, let xMax, let zMax { return FamilyOpening(xMin: xMin, xMax: xMax, zMin: zMin, zMax: zMax) }
        // Last resort: the extents of the solids for the first type.
        let ev = FamilyEvaluator.evaluate(def, typeName: def.types.first?.name ?? "")
        let b = ev.bounds
        guard !b.isEmpty, b.max.x - b.min.x > Tolerance.length, b.max.z - b.min.z > Tolerance.length else {
            warn("no wall opening could be determined; instances will not cut their host wall.")
            return nil
        }
        warn("the wall opening was taken from the extents of the family's solids and does not follow its parameters.")
        return FamilyOpening(xMin: .expr(fmt(b.min.x)), xMax: .expr(fmt(b.max.x)), zMin: .expr(fmt(b.min.z)), zMax: .expr(fmt(b.max.z)))
    }

    /// Adds Width/Height parameters if needed and a panel (doors) or frame and glass (windows) driven by them.
    static func synthesizeInsertGeometry(_ def: inout FamilyDefinition, builtIn: [String: String]) {
        let width = builtIn["width"] ?? "Width", height = builtIn["height"] ?? "Height"
        if def.parameter(named: width) == nil {
            def.parameters.append(FamilyParameter(name: width, type: .length, group: .dimensions, isBuiltIn: true))
            for i in def.types.indices { def.types[i].values[width] = .double(def.template == .door ? 0.9 : 1.2) }
        }
        if def.parameter(named: height) == nil {
            def.parameters.append(FamilyParameter(name: height, type: .length, group: .dimensions, isBuiltIn: true))
            for i in def.types.indices { def.types[i].values[height] = .double(def.template == .door ? 2.1 : 1.2) }
        }
        let w = "(\(width))", h = "(\(height))"
        func box(_ n: String, _ x0: String, _ x1: String, _ y0: String, _ y1: String, _ z0: String, _ z1: String, _ sub: FamilySubcategory, plan: Bool = true) -> FamilySolid {
            var s = FamilySolid(name: n, profile: .rectangle(xMin: .expr(x0), xMax: .expr(x1), yMin: .expr(y0), yMax: .expr(y1)),
                                zMin: .expr(z0), zMax: .expr(z1), subcategory: sub, visibleInPlan: plan)
            s.id = "\(def.name)/generated/\(n)"
            return s
        }
        if def.template == .door {
            def.solids.append(box("Panel", "-\(w) / 2", "\(w) / 2", "-0.02", "0.02", "0", h, .panel, plan: false))
            var swing = FamilyLine(shape: .arc(center: FamilyPoint("-\(w) / 2", "0"), radius: w, startDegrees: "-90", sweepDegrees: "90"), subcategory: .swing)
            swing.id = "\(def.name)/generated/swing"
            def.planLines.append(swing)
        } else {
            def.solids.append(box("Frame Left", "-\(w) / 2", "-\(w) / 2 + 0.05 m", "-0.05", "0.05", "0", h, .frame))
            def.solids.append(box("Frame Right", "\(w) / 2 - 0.05 m", "\(w) / 2", "-0.05", "0.05", "0", h, .frame))
            def.solids.append(box("Glass", "-\(w) / 2 + 0.05 m", "\(w) / 2 - 0.05 m", "-0.012", "0.012", "0", h, .glass, plan: false))
        }
    }
