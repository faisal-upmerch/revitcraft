import CoreGraphics
import Foundation
import PDFKit
import Synchronization
import Testing
import ArcusGeometry
import ArcusDomain
@testable import ArcusOutput

private let pt = 72.0 / 0.0254

private func job(_ f: Fixture, _ items: [PDFExportItem], dir: URL = Fixture.tempDir()) -> PDFExportJob {
    PDFExportJob(items: items, outputDirectory: dir)
}

private func text(_ url: URL, page: Int) -> String {
    PDFDocument(url: url)?.page(at: page)?.string ?? ""
}

@Suite("PDF export")
struct PDFExportTests {
    let f = Fixture.shared

    @Test func combinedSetKeepsJobOrderAndPaperSizes() async throws {
        // Deliberately not in sheet-number order.
        let j = job(f, [.sheet(f.sheetSchedule), .sheet(f.sheetPlan), .sheet(f.sheetSection)])
        let r = try await PDFExporter.export(f.model, job: j)
        #expect(r.files.count == 1)
        #expect(r.pageCount == 3 && r.vectorPages == 3 && r.rasterPages == 0)
        let sizes = pageSizes(r.files[0])
        #expect(sizes.count == 3)
        #expect(abs(sizes[0].width - 0.9144 * pt) < 0.5 && abs(sizes[0].height - 0.6096 * pt) < 0.5)   // ARCH D 36 × 24 in
        #expect(abs(sizes[1].width - 0.841 * pt) < 0.5 && abs(sizes[1].height - 0.594 * pt) < 0.5)     // A1
        #expect(text(r.files[0], page: 0).contains("A601"))
        #expect(text(r.files[0], page: 1).contains("A101"))
        #expect(text(r.files[0], page: 2).contains("A201"))
    }

    @Test func viewsExportOnViewPaperFittedAndPortrait() async throws {
        var j = job(f, [.view(f.plan)])
        j.viewPaper = .a3
        let r = try await PDFExporter.export(f.model, job: j)
        let s = pageSizes(r.files[0])[0]
        #expect(abs(s.width - 0.420 * pt) < 0.5 && abs(s.height - 0.297 * pt) < 0.5)
        j.viewLandscape = false
        j.overwrite = .replace
        let p = try await PDFExporter.export(f.model, job: j)
        let ps = pageSizes(p.files[0])[0]
        #expect(ps.width < ps.height)
    }

    @Test func actualSizeWarnsWhenTheViewDoesNotFit() async throws {
        var j = job(f, [.view(f.plan)])
        j.viewPaper = .a4
        j.zoom = .actual
        let small = try await PDFExporter.export(f.model, job: j)
        #expect(!small.warnings.contains { $0.contains("clipped") })   // 10 m at 1:100 fits A4
        // Make the plan 1:10 so it can't fit.
        let tx = TransactionContext(model: f.model, name: "Scale")
        tx.update(f.plan) { $0.view?.scale = 10 }
        let m = try tx.commit().model
        j.overwrite = .replace
        let big = try await PDFExporter.export(m, job: j)
        #expect(big.warnings.contains { $0.contains("clipped") && $0.contains("1 : 10") })
    }

    @Test func textIsRealTextWithSheetNumberNameAndDimensions() async throws {
        let r = try await PDFExporter.export(f.model, job: job(f, [.sheet(f.sheetPlan)]))
        let s = text(r.files[0], page: 0)
        #expect(s.contains("A101"))
        #expect(s.contains("Ground Floor Plan"))
        #expect(s.contains("LIBRARY ENTRANCE"))
        // The dimension's own label as generated by the view.
        let g = ViewGraphicsBuilder(model: f.model, view: f.model[f.plan]!).build()
        let dimText = g.items.first { $0.elementID == f.dimension }?.primitives.compactMap { p -> String? in
            if case .text(let t) = p { return t.string }; return nil
        }.first
        #expect(dimText != nil)
        if let dimText { #expect(s.contains(dimText)) }
    }

    @Test func pagesContainVectorOperatorsAndNoImages() async throws {
        let r = try await PDFExporter.export(f.model, job: job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSchedule), .view(f.plan)]))
        let doc = CGPDFDocument(r.files[0] as CFURL)!
        for i in 1...doc.numberOfPages {
            let page = doc.page(at: i)!
            #expect(imageXObjectCount(page) == 0)
            let ops = operatorCounts(page)
            #expect(ops.xobjects == 0)
            #expect(ops.lines > 10)
            #expect(ops.text > 0)
        }
        // Door swings / view-title circles are true arcs → Bézier curve operators.
        #expect(operatorCounts(doc.page(at: 1)!).curves > 0)
    }

    @Test func bookmarksHaveSheetTitles() async throws {
        let r = try await PDFExporter.export(f.model, job: job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection), .view(f.plan)]))
        let doc = PDFDocument(url: r.files[0])!
        let root = try #require(doc.outlineRoot)
        #expect(root.numberOfChildren == 3)
        #expect(root.child(at: 0)?.label == "A101 – Ground Floor Plan")
        #expect(root.child(at: 1)?.label == "A201 – Building Sections")
        #expect(root.child(at: 2)?.label == "Floor Plan: Level 1")
        #expect(root.child(at: 1)?.destination?.page.map { doc.index(for: $0) } == 1)
        var j = job(f, [.sheet(f.sheetPlan)])
        j.bookmarks = false
        let none = try await PDFExporter.export(f.model, job: j)
        #expect(PDFDocument(url: none.files[0])!.outlineRoot == nil)
    }

    @Test func sectionMarkerLinksToTheSheetWhereTheSectionIsPlaced() async throws {
        let r = try await PDFExporter.export(f.model, job: job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection)]))
        let doc = PDFDocument(url: r.files[0])!
        let links = doc.page(at: 0)!.annotations.filter { $0.type == "Link" }
        #expect(!links.isEmpty)
        let targets = links.compactMap { a -> Int? in
            let dest = a.destination ?? (a.action as? PDFActionGoTo)?.destination
            return dest?.page.map { doc.index(for: $0) }
        }
        #expect(targets.contains(1))
        // The section sheet has no markers pointing elsewhere.
        #expect(doc.page(at: 1)!.annotations.filter { $0.type == "Link" }.isEmpty)
    }

    @Test func noLinksWhenDisabledOrTargetNotExported() async throws {
        var j = job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection)])
        j.internalLinks = false
        let off = try await PDFExporter.export(f.model, job: j)
        #expect(PDFDocument(url: off.files[0])!.page(at: 0)!.annotations.isEmpty)
        let alone = try await PDFExporter.export(f.model, job: job(f, [.sheet(f.sheetPlan)]))
        #expect(PDFDocument(url: alone.files[0])!.page(at: 0)!.annotations.isEmpty)
    }

    @Test func standaloneViewMarkersLinkToPlacedSections() async throws {
        let r = try await PDFExporter.export(f.model, job: job(f, [.view(f.plan), .sheet(f.sheetSection)]))
        let doc = PDFDocument(url: r.files[0])!
        #expect(doc.page(at: 0)!.annotations.contains { $0.type == "Link" })
    }

    @Test func metadataHasTitleAndCreatorButNoAuthor() async throws {
        var j = job(f, [.sheet(f.sheetPlan)])
        j.creator = "Arcus 1.0"
        let r = try await PDFExporter.export(f.model, job: j)
        let attrs = PDFDocument(url: r.files[0])!.documentAttributes ?? [:]
        #expect(attrs[PDFDocumentAttribute.titleAttribute] as? String == "Harbour Library")
        #expect(attrs[PDFDocumentAttribute.creatorAttribute] as? String == "Arcus 1.0")
        #expect(attrs[PDFDocumentAttribute.producerAttribute] != nil)
        #expect(attrs[PDFDocumentAttribute.authorAttribute] == nil)
    }

    @Test func individualFilesAreNamedPerItem() async throws {
        var j = job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection), .view(f.plan)])
        j.combined = false
        let r = try await PDFExporter.export(f.model, job: j)
        #expect(r.files.map(\.lastPathComponent) == ["A101 - Ground Floor Plan.pdf", "A201 - Building Sections.pdf", "Floor Plan - Level 1.pdf"])
        #expect(r.pageCount == 3)
        for u in r.files { #expect(pageSizes(u).count == 1) }
        j.naming = .viewName
        j.outputDirectory = Fixture.tempDir()
        let byName = try await PDFExporter.export(f.model, job: j)
        #expect(byName.files.map(\.lastPathComponent) == ["Ground Floor Plan.pdf", "Building Sections.pdf", "Level 1.pdf"])
    }

    @Test func fileNamesAreSanitized() throws {
        let tx = TransactionContext(model: f.model, name: "Names")
        tx.update(f.sheetPlan) { $0.name = "Plan: Level 1/2\u{0007}\tWest\nWing" }
        tx.update(f.sheetSection) { $0.name = String(repeating: "Ω", count: 400) }
        tx.update(f.plan) { $0.name = "...hidden" }
        let m = try tx.commit().model
        let a = PDFExporter.fileName(for: .sheet(f.sheetPlan), model: m, naming: .sheetNumberAndName)
        #expect(a == "A101 - Plan- Level 1-2 West Wing.pdf")
        let b = PDFExporter.fileName(for: .sheet(f.sheetSection), model: m, naming: .viewName)
        #expect(b.count <= 200 && b.utf8.count <= 255 && b.hasSuffix(".pdf"))
        let c = PDFExporter.fileName(for: .view(f.plan), model: m, naming: .viewName)
        #expect(c == "hidden.pdf")
        let d = PDFExporter.fileName(for: .view(f.plan), model: m, naming: .custom("   "))
        #expect(d == "Untitled.pdf")
        for n in [a, b, c, d] { #expect(!n.contains("/") && !n.contains(":") && !n.unicodeScalars.contains { $0.value < 0x20 }) }
    }

    @Test func customNamingTemplateExpandsTokens() {
        let n = PDFExporter.fileName(for: .sheet(f.sheetPlan), model: f.model, naming: .custom("{Project Number} {Sheet Number} {Sheet Name} {Date}"))
        #expect(n.hasPrefix("HL-2026 A101 Ground Floor Plan "))
        #expect(n.range(of: #"\d{4}-\d{2}-\d{2}\.pdf$"#, options: .regularExpression) != nil)
        let v = PDFExporter.fileName(for: .view(f.plan), model: f.model, naming: .custom("{Sheet Number}_{View Name}"))
        #expect(v == "A101_Level 1.pdf")
    }

    @Test func duplicateNamesWithinAJobAreMadeUnique() async throws {
        var j = job(f, [.sheet(f.sheetPlan), .sheet(f.sheetPlan)])
        j.combined = false
        let r = try await PDFExporter.export(f.model, job: j)
        #expect(r.files.map(\.lastPathComponent) == ["A101 - Ground Floor Plan.pdf", "A101 - Ground Floor Plan (2).pdf"])
    }

    @Test func failPolicyReportsConflictsWithoutWriting() async throws {
        let dir = Fixture.tempDir()
        let existing = dir.appendingPathComponent("A101 - Ground Floor Plan.pdf")
        try Data("old".utf8).write(to: existing)
        var j = job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection)], dir: dir)
        j.combined = false
        #expect(PDFExporter.conflicts(f.model, job: j) == [existing])
        await #expect(throws: PDFExportError.self) { _ = try await PDFExporter.export(f.model, job: j) }
        do {
            _ = try await PDFExporter.export(f.model, job: j)
        } catch let e as PDFExportError {
            #expect(e.conflicts == [existing])
        }
        #expect(try Data(contentsOf: existing) == Data("old".utf8))
        #expect(!FileManager.default.fileExists(atPath: dir.appendingPathComponent("A201 - Building Sections.pdf").path))
    }

    @Test func skipPolicyLeavesExistingFilesAndRendersTheRest() async throws {
        let dir = Fixture.tempDir()
        let existing = dir.appendingPathComponent("A101 - Ground Floor Plan.pdf")
        try Data("old".utf8).write(to: existing)
        var j = job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection)], dir: dir)
        j.combined = false
        j.overwrite = .skip
        let r = try await PDFExporter.export(f.model, job: j)
        #expect(r.skippedExisting == [existing])
        #expect(r.files.map(\.lastPathComponent) == ["A201 - Building Sections.pdf"])
        #expect(r.pageCount == 1)
        #expect(try Data(contentsOf: existing) == Data("old".utf8))
    }

    @Test func replaceAndUniquifyPolicies() async throws {
        let dir = Fixture.tempDir()
        let existing = dir.appendingPathComponent("Arcus Set.pdf")
        try Data("old".utf8).write(to: existing)
        var j = job(f, [.sheet(f.sheetPlan)], dir: dir)
        j.overwrite = .uniquify
        let u = try await PDFExporter.export(f.model, job: j)
        #expect(u.files.map(\.lastPathComponent) == ["Arcus Set (2).pdf"])
        #expect(try Data(contentsOf: existing) == Data("old".utf8))
        j.overwrite = .replace
        let r = try await PDFExporter.export(f.model, job: j)
        #expect(r.files == [existing])
        #expect(PDFDocument(url: existing)?.pageCount == 1)
        let names = try FileManager.default.contentsOfDirectory(atPath: dir.path).sorted()
        #expect(names == ["Arcus Set (2).pdf", "Arcus Set.pdf"])
    }

    @Test func cancellationDeletesPartialOutputAndKeepsExistingFiles() async throws {
        let dir = Fixture.tempDir()
        let existing = dir.appendingPathComponent("A101 - Ground Floor Plan.pdf")
        try Data("keep me".utf8).write(to: existing)
        var j = job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection), .sheet(f.sheetSchedule)], dir: dir)
        j.combined = false
        j.overwrite = .replace
        let pages = Mutex(0)
        await #expect(throws: CancellationError.self) {
            _ = try await PDFExporter.export(f.model, job: j, progress: { _, _ in pages.withLock { $0 += 1 } },
                                             isCancelled: { pages.withLock { $0 } >= 2 })
        }
        #expect(try FileManager.default.contentsOfDirectory(atPath: dir.path) == ["A101 - Ground Floor Plan.pdf"])
        #expect(try Data(contentsOf: existing) == Data("keep me".utf8))
    }

    @Test func failedMoveRollsBackFilesAlreadyReplaced() async throws {
        let dir = Fixture.tempDir()
        let first = dir.appendingPathComponent("A101 - Ground Floor Plan.pdf")
        try Data("original".utf8).write(to: first)
        // A directory where the second PDF should go makes its move fail after the first file was replaced.
        let blocker = dir.appendingPathComponent("A201 - Building Sections.pdf", isDirectory: true)
        try FileManager.default.createDirectory(at: blocker, withIntermediateDirectories: false)
        var j = job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection)], dir: dir)
        j.combined = false
        j.overwrite = .replace
        await #expect(throws: PDFExportError.self) { _ = try await PDFExporter.export(f.model, job: j) }
        #expect(try Data(contentsOf: first) == Data("original".utf8))
        var isDir: ObjCBool = false
        #expect(FileManager.default.fileExists(atPath: blocker.path, isDirectory: &isDir) && isDir.boolValue)
        #expect(try FileManager.default.contentsOfDirectory(atPath: dir.path).sorted() == ["A101 - Ground Floor Plan.pdf", "A201 - Building Sections.pdf"])
    }

    @Test func progressIsReportedPerPageWithLabelsOffTheMainThread() async throws {
        let log = Mutex<[(Double, String, Bool)]>([])
        _ = try await PDFExporter.export(f.model, job: job(f, [.sheet(f.sheetPlan), .sheet(f.sheetSection)]),
                                         progress: { p, label in log.withLock { $0.append((p, label, Thread.isMainThread)) } })
        let entries = log.withLock { $0 }
        #expect(entries.map(\.1) == ["A101 – Ground Floor Plan", "A201 – Building Sections"])
        #expect(entries.map(\.0) == [0.5, 1.0])
        #expect(entries.allSatisfy { !$0.2 })
    }

    @Test func cropBoundariesAndGuidesOnlyWhenRequested() async throws {
        let tx = TransactionContext(model: f.model, name: "Guides")
        tx.update(f.sheetPlan) { $0.sheet?.guideGridSpacing = 0.05 }
        let m = try tx.commit().model
        var j = job(f, [.sheet(f.sheetPlan)])
        let hidden = try await PDFExporter.export(m, job: j)
        j.hideCropBoundaries = false
        j.outputDirectory = Fixture.tempDir()
        let shown = try await PDFExporter.export(m, job: j)
        let a = operatorCounts(CGPDFDocument(hidden.files[0] as CFURL)!.page(at: 1)!)
        let b = operatorCounts(CGPDFDocument(shown.files[0] as CFURL)!.page(at: 1)!)
        // A1 at 50 mm spacing: 16 vertical + 11 horizontal guide lines, plus the viewport crop outline.
        #expect(b.lines >= a.lines + 27)
    }

    @Test func scheduleOnSheetAndStandaloneScheduleAreVectorText() async throws {
        let r = try await PDFExporter.export(f.model, job: job(f, [.sheet(f.sheetSchedule), .view(f.doorSchedule)]))
        for i in 0..<2 {
            let s = text(r.files[0], page: i)
            #expect(s.contains("DOOR SCHEDULE"))
            #expect(s.contains("D-01") && s.contains("D-02"))
        }
    }

    @Test func invalidItemsAreRejectedUpFront() async throws {
        let dir = Fixture.tempDir()
        await #expect(throws: PDFExportError.self) { _ = try await PDFExporter.export(f.model, job: job(f, [.sheet(f.plan)], dir: dir)) }
        await #expect(throws: PDFExportError.self) { _ = try await PDFExporter.export(f.model, job: job(f, [.view(ElementID(9_999_999))], dir: dir)) }
        await #expect(throws: PDFExportError.self) { _ = try await PDFExporter.export(f.model, job: job(f, [], dir: dir)) }
        #expect(try FileManager.default.contentsOfDirectory(atPath: dir.path).isEmpty)
    }

    @Test func suppliedGraphicsAreUsedOncePerView() async throws {
        let calls = Mutex<[ElementID: Int]>([:])
        let m = f.model
        let r = try await PDFExporter.export(m, job: job(f, [.sheet(f.sheetPlan), .view(f.plan)]), graphics: { v in
            calls.withLock { $0[v.id, default: 0] += 1 }
            return ViewGraphicsBuilder(model: m, view: v).build()
        })
        #expect(r.pageCount == 2)
        #expect(calls.withLock { $0[f.plan] } == 1)
    }
}
