pub struct CmdInfo {
    pub label: &'static str,
    pub icon: Icon,
    pub tip: &'static str,
    pub keys: &'static str,
}

const fn ci(label: &'static str, icon: Icon, tip: &'static str, keys: &'static str) -> CmdInfo {
    CmdInfo { label, icon, tip, keys }
}

