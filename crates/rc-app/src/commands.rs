/// Keyboard shortcuts (two-letter sequences); user overrides replace the defaults.
#[derive(Clone, Debug, Default, serde::Serialize, serde::Deserialize)]
pub struct Shortcuts {
    pub custom: std::collections::BTreeMap<String, String>,
}

impl Shortcuts {
    pub fn keys(&self, c: Cmd) -> String {
        self.custom.get(&c.key_name()).cloned().unwrap_or_else(|| c.info().keys.to_string())
    }
    /// The command for a typed key sequence, if it completes one.
    pub fn lookup(&self, seq: &str) -> Option<Cmd> {
        Cmd::ALL.iter().copied().find(|c| {
            let k = self.keys(*c);
            !k.is_empty() && k.split(',').any(|alt| alt.trim().eq_ignore_ascii_case(seq))
        })
    }
    /// Is `seq` a prefix of some shortcut (so we keep listening)?
    pub fn is_prefix(&self, seq: &str) -> bool {
        Cmd::ALL.iter().any(|c| self.keys(*c).split(',').any(|alt| {
            let alt = alt.trim();
            alt.len() > seq.len() && alt.to_ascii_uppercase().starts_with(&seq.to_ascii_uppercase())
        }))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shortcuts_are_unique() {
        let s = Shortcuts::default();
        let mut seen = std::collections::HashMap::new();
        for c in Cmd::ALL {
            let k = s.keys(*c);
            if k.is_empty() {
                continue;
            }
            if let Some(prev) = seen.insert(k.clone(), *c) {
                panic!("{k} is used by {prev:?} and {c:?}");
            }
        }
        assert_eq!(s.lookup("WA"), Some(Cmd::Wall));
        assert!(s.is_prefix("W"));
    }
}
